#[wasm_bindgen]
pub struct InteractiveChatSession {
    context_vector: VsaVector,
    last_phase_alpha: i32,
    codebook: [[i32; 8]; VOCAB_SIZE],
    projection_matrix: [[i16; 512]; 8],
}

#[wasm_bindgen]
impl InteractiveChatSession {
    #[wasm_bindgen(constructor)]
    pub fn new() -> Self {
        Self {
            context_vector: VsaVector::zero(),
            last_phase_alpha: 0,
            codebook: DEFAULT_CODEBOOK_COORDINATES,
            projection_matrix: PRE_TRAINED_PROJECTION_MATRIX,
        }
    }

    pub fn reset(&mut self) {
        self.context_vector = VsaVector::zero();
        self.last_phase_alpha = 0;
    }

    pub fn load_custom_codebook(&mut self, flat_coords: &[i32]) -> bool {
        if flat_coords.len() != VOCAB_SIZE * 8 {
            return false;
        }
        for i in 0..VOCAB_SIZE {
            for j in 0..8 {
                self.codebook[i][j] = flat_coords[i * 8 + j];
            }
        }
        true
    }

    pub fn process_input_run(&mut self, input: &str) -> String {
        let (tokens, count) = UnicodeLexicalParser::parse_runs(input);

        if count == 0 {
            return "ERR: Invalid or non-printable ASCII runs".to_string();
        }

        for i in 0..count {
            let seed = tokens[i].compute_vsa_seed();
            let basis = VsaVector::deterministic_basis(seed);
            self.context_vector = self.context_vector.bundle(&basis);
        }

        let mut output_str = String::new();
        let mut generated_count = 0;

        let mut diag_snapped = [0i32; 8];
        let mut diag_chi = 0;
        let mut diag_delta = 0;
        let mut diag_alpha = 0;
        let mut last_word = "";

        while generated_count < 3 {
            let raw_coords = self.context_vector.project_to_8d_with_matrix(&self.projection_matrix);

            let mut warped_coords = raw_coords;
            let warp_factor = (self.last_phase_alpha as i64 * 4) as i32;
            for j in 0..8 {
                if j % 2 == 0 {
                    warped_coords[j] = warped_coords[j].saturating_add(warp_factor);
                } else {
                    warped_coords[j] = warped_coords[j].saturating_sub(warp_factor);
                }
            }

            let snapped = E8LatticeSnapper::snap(warped_coords);
            let (chi, delta, alpha) = CordicHopfEngine::project_to_hopf(snapped);
            self.last_phase_alpha = alpha;

            if generated_count == 0 {
                diag_snapped = snapped;
                diag_chi = chi;
                diag_delta = delta;
                diag_alpha = alpha;
            }

            let weights = GeometricAttention::compute_attention_weights(snapped, &self.codebook);

            let mut best_idx = 0;
            let mut max_weight = -1;
            for i in 0..VOCAB_SIZE {
                if weights[i] > max_weight {
                    max_weight = weights[i];
                    best_idx = i;
                }
            }

            let predicted_word = VOCABULARY[best_idx];
            last_word = predicted_word;
            output_str.push_str(predicted_word);
            if generated_count < 2 {
                output_str.push_str(" ");
            }
            generated_count += 1;

            let p_token = LexicalToken {
                bytes: {
                    let mut b = [0u8; 16];
                    let p_bytes = predicted_word.as_bytes();
                    let len = p_bytes.len().min(16);
                    for j in 0..len {
                        b[j] = p_bytes[j];
                    }
                    b
                },
                len: predicted_word.len(),
            };
            let p_seed = p_token.compute_vsa_seed();
            let p_basis = VsaVector::deterministic_basis(p_seed);
            self.context_vector = self.context_vector.bundle(&p_basis);
        }

        format!(
            "{{\"completion\":\"{}\", \"snapped\":[{},{},{},{},{},{},{},{}], \"chi\":{:.4}, \"delta\":{:.4}, \"alpha\":{:.4}, \"winner\":\"{}\"}}",
            output_str,
            diag_snapped[0], diag_snapped[1], diag_snapped[2], diag_snapped[3],
            diag_snapped[4], diag_snapped[5], diag_snapped[6], diag_snapped[7],
            (diag_chi as f32) / 16384.0, (diag_delta as f32) / 16384.0, (diag_alpha as f32) / 16384.0,
            last_word
        )
    }
}

// =====================================================================
// 8. BROWSER-COMPATIBLE TRAINING ADAPTER
// =====================================================================

#[wasm_bindgen]
pub struct BrowserTrainingHarness {
    codebook: [[i32; 8]; VOCAB_SIZE],
}

#[wasm_bindgen]
impl BrowserTrainingHarness {
    #[wasm_bindgen(constructor)]
    pub fn new() -> Self {
        Self {
            codebook: DEFAULT_CODEBOOK_COORDINATES,
        }
    }

    pub fn train_on_corpus(&mut self, corpus: &str, epochs: u32, learning_rate_q16: i32) -> String {
        let (tokens, count) = UnicodeLexicalParser::parse_runs(corpus);

        if count < 2 {
            return "{\"status\":\"error\", \"message\":\"Corpus must contain at least 2 valid words.\"}".to_string();
        }

        let mut total_loss = 0i64;
        let mut steps = 0;

        for _ in 0..epochs {
            for i in 0..(count - 1) {
                let current_word = tokens[i];
                let next_word = tokens[i + 1];

                let mut target_idx = None;
                let next_word_str = std::str::from_utf8(&next_word.bytes[0..next_word.len]).unwrap_or("");
                for v in 0..VOCAB_SIZE {
                    if VOCABULARY[v] == next_word_str {
                        target_idx = Some(v);
                        break;
                    }
                }

                let target_v = match target_idx {
                    Some(v) => v,
                    None => continue,
                };

                let seed = current_word.compute_vsa_seed();
                let basis = VsaVector::deterministic_basis(seed);
                let raw_coords = basis.project_to_8d_with_matrix(&PRE_TRAINED_PROJECTION_MATRIX);
                let snapped = E8LatticeSnapper::snap(raw_coords);

                let weights = GeometricAttention::compute_attention_weights(snapped, &self.codebook);

                let target_weight = weights[target_v].max(1);
                let loss = 65536 - target_weight;
                total_loss += loss as i64;
                steps += 1;

                let gradient_scalar = (loss as i64 * learning_rate_q16 as i64) >> 16;
                for j in 0..8 {
                    let grad = ((snapped[j] as i64) * gradient_scalar) >> 16;
                    self.codebook[target_v][j] = self.codebook[target_v][j].saturating_add(grad as i32);
                }
            }
        }

        let avg_loss = if steps > 0 { total_loss / steps } else { 0 };

        let mut coords_arr = String::new();
        coords_arr.push_str("[");
        for i in 0..VOCAB_SIZE {
            for j in 0..8 {
                coords_arr.push_str(&self.codebook[i][j].to_string());
                if i < VOCAB_SIZE - 1 || j < 7 {
                    coords_arr.push_str(",");
                }
            }
        }
        coords_arr.push_str("]");

        format!(
            "{{\"status\":\"success\", \"average_loss\":{:.4}, \"steps\":{}, \"updated_coordinates\":{}}}",
            (avg_loss as f32) / 65536.0,
            steps,
            coords_arr
        )
    }
}
