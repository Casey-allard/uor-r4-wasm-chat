// =====================================================================
// 2. UNICODE LEXICAL PARSER
// =====================================================================

#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub struct LexicalToken {
    pub bytes: [u8; 16],
    pub len: usize,
}

impl LexicalToken {
    pub const fn new() -> Self {
        Self {
            bytes: [0u8; 16],
            len: 0,
        }
    }

    /// Shift-Add-Xor Hash for multiplier-free seed generation
    pub const fn compute_vsa_seed(&self) -> u64 {
        let mut hash: u64 = 5381;
        let mut i = 0;
        while i < self.len {
            let byte = self.bytes[i] as u64;
            hash = (hash ^ byte).wrapping_add((hash ^ byte) << 5);
            i += 1;
        }
        hash
    }
}

pub struct UnicodeLexicalParser;

impl UnicodeLexicalParser {
    pub fn parse_runs(input: &str) -> ([LexicalToken; MAX_TOKENS], usize) {
        let mut tokens = [LexicalToken::new(); MAX_TOKENS];
        let mut count = 0;
        let trimmed = input.trim();

        if trimmed.is_empty() {
            return (tokens, 0);
        }

        for word in trimmed.split_whitespace() {
            if count >= MAX_TOKENS {
                break;
            }

            let mut token = LexicalToken::new();
            let mut len = 0;

            for byte in word.bytes() {
                if len >= 16 {
                    break;
                }
                let normalized = if byte >= b'A' && byte <= b'Z' {
                    byte + 32
                } else {
                    byte
                };

                if (normalized >= b'a' && normalized <= b'z') || (normalized >= b'0' && normalized <= b'9') {
                    token.bytes[len] = normalized;
                    len += 1;
                }
            }

            if len > 0 {
                token.len = len;
                tokens[count] = token;
                count += 1;
            }
        }

        (tokens, count)
    }
}

// =====================================================================
// 3. VECTOR SYMBOLIC ARCHITECTURE (VSA) BINDING LAYER
// =====================================================================

#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub struct VsaVector {
    pub elements: [i16; VSA_DIM],
}

impl VsaVector {
    pub const fn zero() -> Self {
        Self {
            elements: [0; VSA_DIM],
        }
    }

    pub const fn deterministic_basis(seed: u64) -> Self {
        let mut elements = [0i16; VSA_DIM];
        let mut state = seed;
        let mut i = 0;

        while i < VSA_DIM {
            state = state.wrapping_add(0xf3e9_bc15_a21d_5e83);
            state = (state << 13) | (state >> 51);
            elements[i] = if (state & 1) == 1 { 1 } else { -1 };
            i += 1;
        }

        Self { elements }
    }

    pub const fn bundle(&self, other: &Self) -> Self {
        let mut elements = [0i16; VSA_DIM];
        let mut i = 0;
        while i < VSA_DIM {
            elements[i] = self.elements[i].saturating_add(other.elements[i]);
            i += 1;
        }
        Self { elements }
    }

    pub const fn project_to_8d_with_matrix(&self, matrix: &[[i16; VSA_DIM]; 8]) -> [i32; 8] {
        let mut output = [0i32; 8];
        let mut b = 0;

        while b < 8 {
            let mut dot_sum = 0i64;
            let mut i = 0;
            while i < VSA_DIM {
                dot_sum += (self.elements[i] as i64) * (matrix[b][i] as i64);
                i += 1;
            }
            output[b] = (dot_sum << 1) as i32;
            b += 1;
        }

        output
    }
}

// =====================================================================
// 4. ICOSIAN & E8 LATTICE SNAPPING GATES
// =====================================================================

pub struct E8LatticeSnapper;

impl E8LatticeSnapper {
    pub fn snap(input: [i32; 8]) -> [i32; 8] {
        let mut even_cand = [0i32; 8];
        let mut even_sum = 0i32;
        let mut even_diffs = [0i32; 8];

        for i in 0..8 {
            let val = input[i];
            let shifted = (val + 0x10000) >> 17;
            let rounded_even = shifted << 1;
            even_cand[i] = rounded_even;
            even_sum += rounded_even;
            even_diffs[i] = val - (rounded_even << 16);
        }

        if (even_sum % 4) != 0 {
            let mut best_idx = 0;
            let mut max_err = -1;
            let mut adjust_direction = 2;

            for i in 0..8 {
                let err = even_diffs[i].abs();
                if err > max_err {
                    max_err = err;
                    best_idx = i;
                    adjust_direction = if even_diffs[i] >= 0 { 2 } else { -2 };
                }
            }
            even_cand[best_idx] += adjust_direction;
        }

        let mut odd_cand = [0i32; 8];
        let mut odd_sum = 0i32;
        let mut odd_diffs = [0i32; 8];

        for i in 0..8 {
            let val = input[i];
            let shifted = val >> 17;
            let rounded_odd = (shifted << 1) + 1;
            odd_cand[i] = rounded_odd;
            odd_sum += rounded_odd;
            odd_diffs[i] = val - (rounded_odd << 16);
        }

        if (odd_sum % 4) != 0 {
            let mut best_idx = 0;
            let mut max_err = -1;
            let mut adjust_direction = 2;

            for i in 0..8 {
                let err = odd_diffs[i].abs();
                if err > max_err {
                    max_err = err;
                    best_idx = i;
                    adjust_direction = if odd_diffs[i] >= 0 { 2 } else { -2 };
                }
            }
            odd_cand[best_idx] += adjust_direction;
        }

        let mut even_dist = 0i64;
        let mut odd_dist = 0i64;

        for i in 0..8 {
            let d_even = (input[i] - (even_cand[i] << 16)) as i64;
            let d_odd = (input[i] - (odd_cand[i] << 16)) as i64;
            even_dist += (d_even * d_even) >> 16;
            odd_dist += (d_odd * d_odd) >> 16;
        }

        if even_dist <= odd_dist {
            even_cand
        } else {
            odd_cand
        }
    }
}

// =====================================================================
// 5. CORDIC S^3 HOPF ROUTING ENGINE
// =====================================================================

pub static CORDIC_TABLE: [i32; 15] = [
    25735, 15192, 8026, 4074, 2045, 1023, 511, 255, 127, 63, 31, 15, 7, 3, 1
];

pub struct CordicHopfEngine;

impl CordicHopfEngine {
    pub fn atan2(y: i32, x: i32) -> i32 {
        if x == 0 && y == 0 {
            return 0;
        }

        let mut curr_x = x;
        let mut curr_y = y;
        let mut angle = 0;

        if curr_x < 0 {
            if curr_y >= 0 {
                angle += 51471;
                curr_x = -curr_x;
                curr_y = -curr_y;
            } else {
                angle -= 51471;
                curr_x = -curr_x;
                curr_y = -curr_y;
            }
        }

        for i in 0..15 {
            let prev_x = curr_x;
            if curr_y >= 0 {
                curr_x += curr_y >> i;
                curr_y -= prev_x >> i;
                angle += CORDIC_TABLE[i];
            } else {
                curr_x -= curr_y >> i;
                curr_y += prev_x >> i;
                angle -= CORDIC_TABLE[i];
            }
        }

        angle
    }

    pub fn project_to_hopf(coords: [i32; 8]) -> (i32, i32, i32) {
        let r0 = coords[0];
        let i0 = coords[1];
        let r1 = coords[2];
        let i1 = coords[3];

        let phase_0 = Self::atan2(i0, r0);
        let phase_1 = Self::atan2(i1, r1);

        let delta = phase_1.wrapping_sub(phase_0);
        let alpha = phase_1.wrapping_add(phase_0) >> 1;

        let mag_0 = ((r0 as i64 * r0 as i64) + (i0 as i64 * i0 as i64)).isqrt() as i32;
        let mag_1 = ((r1 as i64 * r1 as i64) + (i1 as i64 * i1 as i64)).isqrt() as i32;
        let chi = Self::atan2(mag_1, mag_0);

        (chi, delta, alpha)
    }
}

// =====================================================================
// 6. MULTIPLICATION-FREE STABLE ATTENTION OPERATOR
// =====================================================================

pub struct GeometricAttention;

impl GeometricAttention {
    pub fn shift_add_exp(neg_val_q16: i32) -> i32 {
        if neg_val_q16 >= 0 {
            return 65536;
        }

        let abs_val = -neg_val_q16;
        if abs_val >= (10 << 16) {
            return 0;
        }

        let y = abs_val + (abs_val >> 1) - (abs_val >> 4) + (abs_val >> 7);
        let integer_part = y >> 16;
        let fractional_part = y & 0xFFFF;

        let linear_term = 65536 - (fractional_part >> 1);
        linear_term >> integer_part
    }

    pub fn compute_attention_weights(query_coords: [i32; 8], codebook: &[[i32; 8]; VOCAB_SIZE]) -> [i32; VOCAB_SIZE] {
        let mut raw_logits = [0i32; VOCAB_SIZE];
        let mut max_logit = i32::MIN;

        for i in 0..VOCAB_SIZE {
            let mut dot = 0i32;
            let centroid = codebook[i];
            for j in 0..8 {
                dot = dot.saturating_add(query_coords[j] * centroid[j]);
            }
            raw_logits[i] = dot;
            if dot > max_logit {
                max_logit = dot;
            }
        }

        let mut exp_sums = [0i32; VOCAB_SIZE];
        let mut sum_accum = 0i32;

        for i in 0..VOCAB_SIZE {
            let diff = (raw_logits[i] - max_logit) >> 10;
            let exp_approx = Self::shift_add_exp(diff);
            exp_sums[i] = exp_approx;
            sum_accum = sum_accum.saturating_add(exp_approx);
        }

        if sum_accum == 0 {
            sum_accum = 1;
        }

        let mut weights = [0i32; VOCAB_SIZE];
        for i in 0..VOCAB_SIZE {
            weights[i] = ((exp_sums[i] as i64 * 65536) / sum_accum as i64) as i32;
        }

        weights
    }
}

